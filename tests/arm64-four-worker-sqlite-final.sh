#!/usr/bin/env bash
# Finalists only: measured Keypool+SQLite at CPUQuota=150%, in a new scratch DB
# per observation. Completely independent of the active Bitcoin node / ckpool.
set -Eeuo pipefail
umask 077
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
[[ "$(uname -m)" == aarch64 ]] || { echo 'AArch64 Pi required' >&2; exit 2; }
[[ -z "$(git -C "$ROOT" status --porcelain --untracked-files=no)" ]] || {
  echo 'Refusing to benchmark modified tracked sources' >&2; exit 2;
}
RUN="${KEYHUNT_FINAL_RUN_DIR:-$ROOT/../runs/arm64-four-final/$(date -u +%Y%m%dT%H%M%SZ)-$$}"
[[ ! -e "$RUN" ]] || { echo "Refusing existing evidence $RUN" >&2; exit 2; }
mkdir -p "$RUN/sources" "$RUN/binaries"
chmod 700 "$RUN"
source "$ROOT/tests/arm64-evidence-archive.sh"
finish_final() {
  local rc=$?
  trap - EXIT
  if find "$RUN" -name FOUND.private -type f -print -quit | grep -q .; then
    echo 'VERIFIED PUZZLE HIT: keep ALL evidence private; archive suppressed.' >&2
    exit "$rc"
  fi
  kh_archive_on_exit "$rc" "$RUN" four-worker-final
}
trap finish_final EXIT
{
  date -u +%FT%TZ
  uname -a
  git -C "$ROOT" rev-parse HEAD
  g++ --version | head -1
  echo "rounds=4 jobs=${KEYHUNT_FINAL_JOBS:-96}"
  echo "bench_budget=${KEYHUNT_FINAL_BUDGET:-960}s"
  echo 'NO interaction with Bitcoin Core, ckpool, miner, or real Keypool SQLite'
  echo 'Every worker uses a separate disposable SQLite DB per observation'
} > "$RUN/provenance.txt"
# Record actual process environment; never stop or reconfigure existing services.
ps -eo pid,ppid,stat,comm,%cpu --sort=-%cpu | head -40 > "$RUN/process-before.txt" || true
for path in Makefile pool/keypoold.py config/keyhunt-arm64-catalog.json \
  tests/arm64-four-worker-sqlite-final.py tests/arm64-four-worker-sqlite-final.sh; do
  mkdir -p "$RUN/sources/$(dirname "$path")"
  cp "$ROOT/$path" "$RUN/sources/$path"
done
python3 "$ROOT/tests/arm64-four-worker-sqlite-final.py" --selftest \
  | tee "$RUN/preflight.log"
# Reuse binaries from the catalog worktree; build only missing/stale finalists.
timeout --signal=TERM --kill-after=10s "${KEYHUNT_FINAL_BUILD_LIMIT:-240}s" \
  make -C "$ROOT" -j2 \
    keyhunt-worker-r3-ecc-sched keyhunt-worker-r7-ecc-pair-unprofiled \
    keyhunt-worker-r7-ecc-fold-unprofiled keyhunt-worker-r2-ripemd-sri \
    2>&1 | tee "$RUN/build.log"
for bin in \
  keyhunt-worker-r3-ecc-sched \
  keyhunt-worker-r7-ecc-pair-unprofiled \
  keyhunt-worker-r7-ecc-fold-unprofiled \
  keyhunt-worker-r2-ripemd-sri; do
  KEYHUNT_WORKER_BIN="$bin" python3 "$ROOT/tests/arm64-worker-protocol.py" \
    >> "$RUN/correctness.log" 2>&1
  KEYHUNT_WORKER_BIN="$bin" python3 "$ROOT/tests/keypool-puzzle20-exhaustive.py" \
    >> "$RUN/correctness.log" 2>&1
  cp "$ROOT/$bin" "$RUN/binaries/$bin"
  sha256sum "$RUN/binaries/$bin" >> "$RUN/binaries.sha256"
done
# The requested CPUQuota=150% MUST be enforced. This is deliberately stricter
# than a low-priority nice command, which would not cap total compute use.
python3 "$ROOT/tests/arm64-four-worker-sqlite-final.py" \
  --jobs "${KEYHUNT_FINAL_JOBS:-96}" \
  --rounds 4 --warmup-jobs "${KEYHUNT_FINAL_WARMUP_JOBS:-8}" \
  --max-seconds "${KEYHUNT_FINAL_BUDGET:-960}" \
  --output "$RUN/observations" 2>&1 | tee "$RUN/benchmark.log"
ps -eo pid,ppid,stat,comm,%cpu --sort=-%cpu | head -40 > "$RUN/process-after.txt" || true
echo "PASS: measured four workers; archive will be generated by EXIT trap."
