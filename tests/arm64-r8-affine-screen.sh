#!/usr/bin/env bash
# R8 measured affine inversion parallel scan, 513 inputs and one inversion.
# 6 widths incl original × two reversed trials × 10 seconds default.
set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RUN="${KEYHUNT_R8_AFFINE_RUN_DIR:-$REPO/../runs/arm64-r8-affine/$(date -u +%Y%m%dT%H%M%SZ)-$$}"
SECONDS_PER_VARIANT="${KEYHUNT_R8_AFFINE_SECONDS:-10}"
REPEATS="${KEYHUNT_R8_AFFINE_REPEATS:-2}"
[[ ! -e "$RUN" ]] || { echo "Run directory exists: $RUN" >&2; exit 2; }
[[ -z "$(git -C "$REPO" status --porcelain --untracked-files=no)" ]] || {
  echo "Refusing dirty tracked source" >&2; exit 2;
}
mkdir -p "$RUN/codegen"
chmod 700 "$RUN"
source "$REPO/tests/arm64-evidence-archive.sh"
trap 'kh_archive_on_exit "$?" "$RUN" r8-affine' EXIT
{
  date -u +%FT%TZ
  git -C "$REPO" rev-parse HEAD
  git -C "$REPO" branch --show-current
  uname -a
  g++ --version | head -1
  grep '^ARM64_CXXFLAGS ' "$REPO/Makefile"
  echo "seconds=$SECONDS_PER_VARIANT repeats=$REPEATS"
  echo "513 nonzero denominators; 1 inversion per batch for all W"
} > "$RUN/provenance.txt"
cp "$REPO/tests/arm64-r8-affine-batchscan.cpp" "$RUN/codegen/source.cpp"
cp "$REPO/secp256k1/IntGroup.cpp" "$RUN/codegen/original-intgroup.cpp"
cp "$REPO/Makefile" "$RUN/codegen/Makefile"
if command -v vcgencmd >/dev/null; then
  { vcgencmd get_throttled; vcgencmd measure_clock arm; vcgencmd measure_temp; } > "$RUN/host-before.txt"
fi
ps -eo pid,ppid,stat,comm,%cpu --sort=-%cpu | head -35 > "$RUN/process-before.txt" || true
make -C "$REPO" -j4 arm64-r8-affine 2>&1 | tee "$RUN/build.log"
cp "$REPO/build/arm64/r8-affine-batchscan" "$RUN/codegen/benchmark.bin"
sha256sum "$RUN/codegen/benchmark.bin" > "$RUN/codegen/binary.sha256"
objdump -drwC "$REPO/build/arm64/r8-affine-batchscan" > "$RUN/codegen/disassembly.txt"
make -C "$REPO" arm64-r8-affine-test 2>&1 | tee "$RUN/correctness.log"
"$REPO/build/arm64/r8-affine-batchscan" \
  --seconds "$SECONDS_PER_VARIANT" --repeats "$REPEATS" \
  2>"$RUN/benchmark-stderr.log" | tee "$RUN/benchmark.csv"
if command -v vcgencmd >/dev/null; then
  { vcgencmd get_throttled; vcgencmd measure_clock arm; vcgencmd measure_temp; } > "$RUN/host-after.txt"
fi
ps -eo pid,ppid,stat,comm,%cpu --sort=-%cpu | head -35 > "$RUN/process-after.txt" || true
python3 "$REPO/tests/arm64-r8-affine-assess.py" "$RUN/benchmark.csv" \
  | tee "$RUN/assessment.txt"
echo "Raw run: $RUN; full archive generated by EXIT handler"
