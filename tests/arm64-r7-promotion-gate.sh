#!/usr/bin/env bash
# Qualification Pi 5: R3-SCHED vs R7-FOLD, then SQLite sandbox at 150% quota.
# Does not run, initialize or alter the real Puzzle 71 campaign.
set -Eeuo pipefail
umask 077
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
MODE="${1:-worker}"
case "$MODE" in
  worker|sqlite) ;;
  *) echo 'Usage: bash tests/arm64-r7-promotion-gate.sh {worker|sqlite}' >&2; exit 2 ;;
esac
[[ "$(uname -m)" == aarch64 ]] || { echo 'Native AArch64 Pi required' >&2; exit 2; }
[[ -z "$(git -C "$ROOT" status --porcelain --untracked-files=no)" ]] || {
  echo 'Refusing modified tracked sources' >&2; exit 2;
}
RUN="${KEYHUNT_QUAL_RUN_DIR:-$ROOT/../runs/arm64-r7-promotion/$(date -u +%Y%m%dT%H%M%SZ)-$$-$MODE}"
[[ ! -e "$RUN" ]] || { echo "Evidence directory already exists: $RUN" >&2; exit 2; }
mkdir -p "$RUN/binaries" "$RUN/sources"
chmod 700 "$RUN"
source "$ROOT/tests/arm64-evidence-archive.sh"
qual_archive() {
  local rc=$?
  trap - EXIT
  if find "$RUN" -name FOUND.private -type f -print -quit | grep -q .; then
    echo 'PRIVATE HIT: archive suppressed. Keep all local evidence private.' >&2
    exit "$rc"
  fi
  kh_archive_on_exit "$rc" "$RUN" r7-promotion
}
trap qual_archive EXIT
{
  date -u +%FT%TZ
  git -C "$ROOT" rev-parse HEAD
  git -C "$ROOT" branch --show-current
  uname -a
  g++ --version | head -1
  echo "mode=$MODE jobs=${KEYHUNT_QUAL_JOBS:-default} repeats=${KEYHUNT_QUAL_REPEATS:-default}"
  echo 'Stage profiling disabled during throughput tests'
  echo 'Only scratch campaigns, never the existing ~/.local/state/keypool/campaign.sqlite3'
} > "$RUN/provenance.txt"
for f in Makefile keyhunt.cpp pool/keypoold.py tests/arm64-r1-worker-ab.py tests/arm64-sqlite-worker-ab.py tests/arm64-r7-promotion-gate.sh tests/keypool-performance-ab.py secp256k1/field_k1_pair_ilp.cpp secp256k1/field_k1_pair_ilp.h hash/ripemd160_neon4.cpp; do
  mkdir -p "$RUN/sources/$(dirname "$f")"
  cp "$ROOT/$f" "$RUN/sources/$f"
done
ps -eo pid,ppid,stat,comm,%cpu --sort=-%cpu | head -35 > "$RUN/process-before.txt" || true
if command -v vcgencmd >/dev/null; then
  { vcgencmd measure_temp; vcgencmd measure_clock arm; vcgencmd get_throttled; } > "$RUN/sensors-before.txt"
fi
if [[ "$MODE" == worker ]]; then
  make -C "$ROOT" -j2 arm64-r7-ecc-test arm64-r7-promotion-worker-test 2>&1 | tee "$RUN/build-and-correctness.log"
else
  # A missing quota is a hard error. Never silently measure an unthrottled run.
  CGREL="$(awk -F: '$1=="0" {print $3}' /proc/self/cgroup)"
  CPUMAX="/sys/fs/cgroup${CGREL}/cpu.max"
  [[ -r "$CPUMAX" ]] || { echo 'cgroup v2 cpu.max unavailable' >&2; exit 2; }
  read -r QUOTA PERIOD < "$CPUMAX"
  echo "cpu.max=$QUOTA $PERIOD ($CPUMAX)" > "$RUN/cpu-quota.txt"
  [[ "$QUOTA" != max ]] || { echo 'No CPU quota. Use systemd-run --user --scope -p CPUQuota=150%' >&2; exit 2; }
  [[ "$QUOTA" =~ ^[0-9]+$ && "$PERIOD" =~ ^[0-9]+$ ]] || { echo 'Invalid cpu.max' >&2; exit 2; }
  (( 100 * QUOTA >= 140 * PERIOD && 100 * QUOTA <= 150 * PERIOD )) || {
    echo "Expected 150% CPU quota, got $QUOTA/$PERIOD" >&2; exit 2;
  }
fi
for bin in keyhunt-worker-r3-ecc-sched keyhunt-worker-r7-ecc-fold-unprofiled; do
  [[ -x "$ROOT/$bin" ]] || { echo "Missing executable $bin. Run worker gate first." >&2; exit 2; }
  cp "$ROOT/$bin" "$RUN/binaries/$bin"
  sha256sum "$RUN/binaries/$bin" >> "$RUN/binaries.sha256"
  objdump -drwC "$ROOT/$bin" > "$RUN/$bin.disassembly.txt"
done
if strings "$ROOT/keyhunt-worker-r7-ecc-fold-unprofiled" | grep -q 'R7_STAGES worker='; then
  echo "Unsafe candidate: R7 stage timing still compiled in" >&2
  exit 2
fi
if [[ "$MODE" == worker ]]; then
  env -u KEYHUNT_R7_STAGE_PROFILE python3 "$ROOT/tests/arm64-r1-worker-ab.py" --control keyhunt-worker-r3-ecc-sched --candidate keyhunt-worker-r7-ecc-fold-unprofiled --jobs "${KEYHUNT_QUAL_JOBS:-256}" --repeats "${KEYHUNT_QUAL_REPEATS:-6}" --run-dir "$RUN/worker" 2>&1 | tee "$RUN/worker-benchmark.log"
else
  env -u KEYHUNT_R7_STAGE_PROFILE python3 "$ROOT/tests/arm64-sqlite-worker-ab.py" --control keyhunt-worker-r3-ecc-sched --candidate keyhunt-worker-r7-ecc-fold --jobs "${KEYHUNT_QUAL_JOBS:-128}" --repeats "${KEYHUNT_QUAL_REPEATS:-4}" --run-dir "$RUN/sqlite" 2>&1 | tee "$RUN/sqlite-benchmark.log"
fi
ps -eo pid,ppid,stat,comm,%cpu --sort=-%cpu | head -35 > "$RUN/process-after.txt" || true
if command -v vcgencmd >/dev/null; then
  { vcgencmd measure_temp; vcgencmd measure_clock arm; vcgencmd get_throttled; } > "$RUN/sensors-after.txt"
fi
echo "Completed $MODE qualification. Archive generated by EXIT handler."
